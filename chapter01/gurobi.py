# Gurobi（gurobipy）を使った線形計画問題（LP）の最小例
# - 連続変数 x1, x2, x3 を用意し
# - 2本の線形制約の下で
# - 線形目的関数を最大化する
#
# これは「線形計画（Linear Programming: LP）」であり、
# 目的関数も制約もすべて一次式（線形）なので、Gurobi内部ではLPソルバ（バリア法/単体法など）で解かれる。

from gurobipy import *

# ----------------------------
# 1) 最適化モデル（数理計画モデル）を作る
# ----------------------------
# Model("lol") は「モデル名」を付けているだけ（ログや保存時に識別しやすい）。
# モデルは「変数」「制約」「目的関数」「各種パラメータ」を保持する箱。
model = Model("lol")

# ----------------------------
# 2) 変数の定義
# ----------------------------
# addVar で意思決定変数を追加する。
# vtype="C" は連続変数（Continuous）を意味する。
# 連続変数は実数（厳密には浮動小数）として扱われ、整数制約がないのでLPになる。
x1 = model.addVar(vtype="C", name="x1")

# x2 は vtype を指定していない。
# Gurobiのデフォルトは連続変数（GRB.CONTINUOUS）なので、x2 も連続変数になる。
# ※「指定してないから整数」ではない点に注意。
x2 = model.addVar(name="x2")

# x3 は上限 ub=30 を指定している。
# 下限 lb は指定していないのでデフォルト 0（非負制約）になる。
# つまり 0 <= x3 <= 30 の連続変数。
# ※ addVar のデフォルト lb は 0。負も許したいなら lb=-GRB.INFINITY 等が必要。
x3 = model.addVar(ub=30, name="x3")

# model.update() は「モデルに追加した変数/制約を内部に確定させる」処理。
# 昔のgurobipyでは addVar 後に update が必要な場面が多かった。
# 現在のバージョンでは多くの場合自動更新され、必須ではないケースも多いが、
# 明示しておくと「変数がモデルに存在する状態」を確実に作れる。
model.update()

# ----------------------------
# 3) 制約の追加（Constraints）
# ----------------------------
# addConstr( 線形式 <= 右辺 ) の形で制約を入れる。
# ここでは資源制約や容量制約っぽい形の「上限制約」2本を追加している。

# 制約1:
# 2*x1 + 1*x2 + 1*x3 <= 60
# これは x1, x2, x3 の線形結合が60以下、という意味。
model.addConstr(2 * x1 + x2 + x3 <= 60)

# 制約2:
# 1*x1 + 2*x2 + 1*x3 <= 60
model.addConstr(x1 + 2 * x2 + x3 <= 60)

# （補足）
# 制約に名前を付けたい場合は、addConstr(..., name="c1") のようにできる。
# 後で IIS 解析やデバッグをするときに制約名があるとかなり楽。

# ----------------------------
# 4) 目的関数の設定（Objective）
# ----------------------------
# setObjective( 目的関数, 最適化方向 ) を指定する。
# ここでは
# maximize  15*x1 + 18*x2 + 30*x3
# を解く。
#
# 直感的には「x1 を1増やすと目的が+15、x2 は+18、x3 は+30」。
# ただし制約があるので無限に増やせるわけではない（制約の範囲で最大化）。
model.setObjective(15 * x1 + 18 * x2 + 30 * x3, GRB.MAXIMIZE)

# ----------------------------
# 5) 最適化（Solve）
# ----------------------------
# optimize() を呼ぶと、Gurobiがモデルを解析して最適解を探索する。
# LPなので、内部ではLPソルバで連続最適解が求まる。
model.optimize()

# ----------------------------
# 6) 解の取り出し
# ----------------------------
# model.getVars() でモデル内の全変数を取得できる。
# v.varName は変数名、v.x は「最適化後の解（最適値）」を表す。
#
# 注意:
# - モデルが infeasible（実行不可能）や unbounded（目的が無限大）だと v.x を読めない/意味がない場合がある。
#   本格的には model.status を見てから取り出すのが安全。
for v in model.getVars():
    print(f"{v.varName} = {v.x}")

# ----------------------------
# （おまけ）このモデルが解いている数理最適化問題の形
# ----------------------------
# 変数:
#   x1 >= 0
#   x2 >= 0
#   0 <= x3 <= 30
#
# 制約:
#   2x1 + x2 + x3 <= 60
#   x1 + 2x2 + x3 <= 60
#
# 目的:
#   maximize 15x1 + 18x2 + 30x3
#
# つまり、線形制約下で線形目的を最大化するLP問題である。
#
# さらに丁寧に書くと、
# - Gurobiは addVar のデフォルトで各変数に下限0を付けるので、負の値は取れない。
# - x3 だけは上限30が追加されている。
