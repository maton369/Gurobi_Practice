"""
prodmix.py:  product mix model

目的（何を解くか）
- 製品ミックス（product mix）を線形計画（LP）として定式化して解く例。
- 製品 i をどれだけ混ぜるか（配合比率）を決め、原材料 k の使用量が上下限を満たす範囲で、
  利益（あるいはコスト）を最適化する。

データの意味
- I: 製品集合
- K: 原材料集合
- p[i]: 製品 i の利益（profit）
- LB[k], UB[k]: 原材料 k の使用量の下限・上限
- a[i,k]: 製品 i を 1 単位作るときに必要な原材料 k の量

注意（重要）
- このコードは「profit（利益）」と書いてあるが、目的関数が `GRB.MINIMIZE` になっているため、
  そのままだと「利益を最小化」してしまう。
- もし本当に利益を最大化したいなら `GRB.MAXIMIZE` にするのが自然である。
  逆に、p[i] が「コスト」なら最小化で整合する。

Copyright (c) by Joao Pedro PEDROSO and Mikio KUBO, 2012
"""

from gurobipy import *

# ------------------------------------------------------------
# 入力データ
# ------------------------------------------------------------
# a[(i,k)] = 製品 i の配合比率が 1 のとき、原材料 k をどれだけ使うか
# 直感的には「製品 i の原材料構成ベクトル」のようなもの。
# 例: a[(4,3)] = 0.85 なら、製品4は原材料3を多く含む。
a = {
    (1, 1): 0.25,
    (1, 2): 0.15,
    (1, 3): 0.30,
    (2, 1): 0.30,
    (2, 2): 0.30,
    (2, 3): 0.10,
    (3, 1): 0.15,
    (3, 2): 0.65,
    (3, 3): 0.05,
    (4, 1): 0.10,
    (4, 2): 0.05,
    (4, 3): 0.85,
}

# I は製品集合、p は「製品iの利益（profit）」の辞書。
I, p = multidict({1: 5, 2: 6, 3: 8, 4: 20})

# K は原材料集合。
# LB[k], UB[k] は原材料kの使用量の下限・上限。
# multidict の値を [LB, UB] の形で持たせ、LB と UB に分解している。
K, LB, UB = multidict(
    {
        1: [0.2, 0.2],  # 原材料1はちょうど 0.2 使う（LB=UB=0.2）
        2: [0.0, 0.35],  # 原材料2は 0.0〜0.35
        3: [0.45, 1.0],  # 原材料3は 0.45〜1.0
    }
)

# ------------------------------------------------------------
# モデル作成
# ------------------------------------------------------------
model = Model("product mix")

# ------------------------------------------------------------
# 変数の定義
# ------------------------------------------------------------
# x[i] = 製品 i の配合比率（混合割合）
# addVar() のデフォルトは連続変数（Continuous）で、かつ下限 lb=0 がデフォルト。
# よって x[i] >= 0 が暗黙に入る（負の配合比率は不可）。
#
# また、後で Σ x[i] = 1 を課すので、x[i] は「確率・割合」のように解釈できる。
x = {}
for i in I:
    x[i] = model.addVar()  # vtype省略 → 連続変数（デフォルト）

model.update()

# ------------------------------------------------------------
# 制約（1）配合比率の総和は 1
# ------------------------------------------------------------
# 全ての製品の配合比率を足すと 1 になる（全体を 100% として正規化）。
#
# 数式で書くと次。
#
# （注意）ユーザー方針に合わせて $$ の前後は空行を入れる。
#
## $$
## \sum_{i \in I} x_i = 1
## $$
#
# この制約があることで、x[i] は「混合物全体に占める製品iの割合」と解釈できる。
model.addConstr(quicksum(x[i] for i in I) == 1)

# ------------------------------------------------------------
# 制約（2）原材料使用量の上下限制約
# ------------------------------------------------------------
# 原材料 k の総使用量は「各製品の使用量 a[i,k] × 配合比率 x[i]」の合計で表せる。
#
# 原材料 k の総使用量：
#
## $$
## \sum_{i \in I} a_{ik}\,x_i
## $$
#
# これが LB[k] 以上、UB[k] 以下であることを課す。
#
# つまり各 k ∈ K について次の2本の不等式を入れている：
#
# $$
# \sum_{i \in I} a_{ik}\,x_i \le \mathrm{UB}_k
# $$
#
# $$
# \sum_{i \in I} a_{ik}\,x_i \ge \mathrm{LB}_k
# $$
#
# この形は「配合設計（blending）」の典型で、品質条件・規格条件を上下限で表すときに頻出する。
for k in K:
    model.addConstr(quicksum(a[i, k] * x[i] for i in I) <= UB[k])
    model.addConstr(quicksum(a[i, k] * x[i] for i in I) >= LB[k])

# ------------------------------------------------------------
# 目的関数
# ------------------------------------------------------------
# p[i] が「profit（利益）」なら、本来は最大化したいのが自然：
#
# $$
# \max \sum_{i \in I} p_i\,x_i
# $$
#
# ただし、このコードは MINIMIZE なので、現状は次を解いている：
#
# $$
# \min \sum_{i \in I} p_i\,x_i
# $$
#
# もし p[i] を「コスト」と見なすなら MINIMIZE で整合する。
# どちらが正しいかはデータ定義（p が利益かコストか）に依存するので、
# 目的の意図に合わせて GRB.MINIMIZE / GRB.MAXIMIZE を選ぶ。
model.setObjective(quicksum(p[i] * x[i] for i in I), GRB.MINIMIZE)

# ------------------------------------------------------------
# 最適化
# ------------------------------------------------------------
# 連続変数 + 線形制約なので LP。
# optimize() でGurobi内部のLPソルバ（単体法/バリア法等）が最適解を求める。
model.optimize()

# ------------------------------------------------------------
# 解の出力
# ------------------------------------------------------------
# x[i].X が最適解における配合比率。
# print は Python3 形式の print() を使う方針。
for i in I:
    print(i, x[i].X)

# ------------------------------------------------------------
# このモデルの全体像（まとめ）
# ------------------------------------------------------------
# 変数：
#
# $$
# x_i \ge 0 \quad (\forall i \in I)
# $$
#
# 制約：
#
# $$
# \sum_{i \in I} x_i = 1
# $$
#
# $$
# \mathrm{LB}_k \le \sum_{i \in I} a_{ik}\,x_i \le \mathrm{UB}_k \quad (\forall k \in K)
# $$
#
# 目的（現状のコード）：
#
# $$
# \min \sum_{i \in I} p_i\,x_i
# $$
#
# 「配合比率を1に正規化」し「原材料の含有量（使用量）が規格範囲内」になるように混ぜて、
# 目的（利益/コスト）を最適化する配合問題の基本形である。
