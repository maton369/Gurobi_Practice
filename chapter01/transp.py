"""
transp.py: a model for the transportation problem

目的（何を解くか）
- 輸送問題（Transportation Problem）の基本モデル。
- 工場（施設）J から顧客 I へ製品を配送する。
- 各顧客 i の需要 d[i] を必ず満たしつつ、
  各工場 j の供給能力（容量）M[j] を超えないように配送量を決める。
- そのときの総輸送コスト（単位コスト c[i,j] × 輸送量 x[i,j]）を最小化する。

数理最適化としての形式
- 目的関数：線形
- 制約：線形（需要の等式制約＋容量の不等式制約）
- 変数：連続（vtype="C"）
  → 線形計画（LP）として解かれる（連続輸送量を許す想定）。
  ※ もし「1単位未満は送れない」「整数単位で送る」なら整数変数にしてILPになる。

データの意味
- I: 顧客集合
- J: 工場（施設）集合
- c[i,j]: 工場 j から顧客 i へ 1単位送るコスト
- d[i]: 顧客 i の需要量（必ず満たす）
- M[j]: 工場 j の供給能力（上限）

Copyright (c) by Joao Pedro PEDROSO and Mikio KUBO, 2012
"""

from gurobipy import *

# ------------------------------------------------------------
# 入力データの定義
# ------------------------------------------------------------
# multidict は「キー集合」と「値辞書」を同時に作るためのユーティリティ。
# 返り値は (keys, dict) のタプルになる。
#
# I は顧客IDの集合（例: [1,2,3,4,5] のようなイテラブル）
# d は需要量の辞書（d[i] で顧客 i の需要）
I, d = multidict({1: 80, 2: 270, 3: 250, 4: 160, 5: 180})  # demand（需要）

# J は工場IDの集合（例: [1,2,3]）
# M は容量の辞書（M[j] で工場 j の最大供給量）
J, M = multidict({1: 500, 2: 500, 3: 500})  # capacity（供給上限）

# c は単位輸送コストの辞書。
# (i,j) をキーにして c[i,j] で参照する。
# ここでは「顧客 i に工場 j から送る」コストを与えている。
c = {
    (1, 1): 4,
    (1, 2): 6,
    (1, 3): 9,  # cost（単位コスト）
    (2, 1): 5,
    (2, 2): 4,
    (2, 3): 7,
    (3, 1): 6,
    (3, 2): 3,
    (3, 3): 4,
    (4, 1): 8,
    (4, 2): 5,
    (4, 3): 3,
    (5, 1): 10,
    (5, 2): 8,
    (5, 3): 4,
}

# ------------------------------------------------------------
# モデル作成
# ------------------------------------------------------------
# Model("transportation") でモデル（最適化問題の器）を作る。
# ここに変数・制約・目的関数を登録し、optimize() で解く。
model = Model("transportation")

# ------------------------------------------------------------
# 変数の作成
# ------------------------------------------------------------
# x[i,j] = 工場 j から顧客 i へ送る量（輸送量）
# vtype="C" は連続変数（Continuous）。輸送量を実数として扱う（分割配送OK）。
#
# 変数を二重ループで全ペア (i,j) について作っている。
# このデータでは c が全ペアを持っているため、結果として全ペア分の変数ができる。
# ※ 一般の輸送問題では、許されないアークがある場合に (i,j) を限定して変数を作ることもある。
x = {}
for i in I:
    for j in J:
        # 変数名を x(i,j) のように付けて、ログやデバッグで追いやすくしている。
        # ここで vtype="C" を指定しているため、x[i,j] は連続変数になる。
        x[i, j] = model.addVar(vtype="C", name="x(%s,%s)" % (i, j))

# addVar で追加した変数を内部的に確定させる。
# 最近のgurobipyでは不要なケースも多いが、古典的書き方として入れている。
model.update()

# ------------------------------------------------------------
# 需要制約（Demand constraints）
# ------------------------------------------------------------
# 各顧客 i について「受け取る総量が需要 d[i] と等しい」を強制する。
# つまり需要は必ず満たす（不足も過剰も不可）。
#
# 制約:
#   Σ_{j in J} x[i,j] = d[i]   for all i in I
#
# quicksum は Python の sum より高速で、Gurobiの線形式構築に向いている。
for i in I:
    # (i,j) in x のチェックは「その変数が存在する場合だけ足す」という安全策。
    # このコードでは全 (i,j) を作っているので常に真だが、
    # アークを間引く実装へ拡張するときにこの書き方が効いてくる。
    model.addConstr(
        quicksum(x[i, j] for j in J if (i, j) in x) == d[i], name="Demand(%s)" % i
    )

# ------------------------------------------------------------
# 容量制約（Capacity constraints）
# ------------------------------------------------------------
# 各工場 j について「出荷する総量が容量 M[j] 以下」を強制する。
#
# 制約:
#   Σ_{i in I} x[i,j] <= M[j]  for all j in J
for j in J:
    model.addConstr(
        quicksum(x[i, j] for i in I if (i, j) in x) <= M[j], name="Capacity(%s)" % j
    )

# ------------------------------------------------------------
# 目的関数（Objective）
# ------------------------------------------------------------
# 総輸送コストを最小化する。
# 各アーク (i,j) で「単位コスト c[i,j] × 輸送量 x[i,j]」を足し合わせる。
#
# 目的:
#   minimize Σ_{i in I} Σ_{j in J} c[i,j] * x[i,j]
#
# ここでは (i,j) in x を走査しているので、変数が存在するアークだけが対象になる。
model.setObjective(quicksum(c[i, j] * x[i, j] for (i, j) in x), GRB.MINIMIZE)

# ------------------------------------------------------------
# 最適化（Solve）
# ------------------------------------------------------------
# optimize() を呼ぶと、Gurobiがモデルを解析して最適解を求める。
# このモデルは LP なので、内部ではLPソルバ（単体法/バリア法など）で解かれる。
model.optimize()

# 最適目的値（最小コスト）を出力
# ユーザー要望に合わせて Python3 形式の print() を使用する。
print("Optimal value:", model.ObjVal)

# ------------------------------------------------------------
# 解の表示（意味のある配送だけ表示）
# ------------------------------------------------------------
# 数値計算の都合で「本当は0」のはずが 1e-12 のような微小値になることがある。
# そのため EPS を閾値にして、十分大きい配送量だけ表示する。
EPS = 1.0e-6

for i, j in x:
    # x[i,j].X は最適化後の変数値（解）。
    # ここで i は「顧客」、j は「工場」を表す点に注意。
    if x[i, j].X > EPS:
        # 表示は "factory j -> customer i に quantity を送る" という意味になる。
        # 注意: 英文メッセージは factory=j, customer=i の順に出している。
        # ユーザー要望に合わせて Python3 形式の print() を使用する。
        print(
            "sending quantity %10s from factory %3s to customer %3s" % (x[i, j].X, j, i)
        )

# ------------------------------------------------------------
# このコードが構築しているモデルのまとめ（数式）
# ------------------------------------------------------------
# 変数:
#   x[i,j] >= 0（連続）  for i in I, j in J
#
# 制約:
#   Σ_{j∈J} x[i,j] = d[i]        for all i∈I   （需要を必ず満たす）
#   Σ_{i∈I} x[i,j] ≤ M[j]        for all j∈J   （工場容量を超えない）
#
# 目的:
#   minimize Σ_{i∈I} Σ_{j∈J} c[i,j] x[i,j]
#
# 輸送問題の典型形であり、ネットワークフロー（最小費用流）としても解釈できる。
# この実装は「ネットワーク専用API」ではなく、一般のLPモデリングAPIで定式化している。
