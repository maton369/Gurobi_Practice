"""
mkp.py: model for the multi-constrained knapsack problem（多次元ナップサック問題: MKP）

目的（何を解くか）
- ナップサック問題（Knapsack）を「制約が複数次元ある」形に一般化した Multi-constrained Knapsack Problem（MKP）を解く。
- 各アイテム j を選ぶかどうかを 0/1（二値）で決め、価値（value）の合計を最大化する。
- ただし制約は 1 本ではなく、次元 i ∈ I ごとに容量制約がある（例：重量・体積・コスト・電力など複数の上限）。

データの意味
- I: 制約次元の集合（dimension）
- J: アイテム集合
- v[j]: アイテム j の価値（value）
- a[i,j]: アイテム j が次元 i の容量をどれだけ消費するか（重み/使用量）
- b[i]: 次元 i の容量（cap）

数理最適化としての形式
- 変数：二値（0/1）
- 目的関数：線形
- 制約：線形（各次元の容量制約）
- よって **0-1整数線形計画（0-1 ILP / MIP）** として解かれる。

# 数式はユーザー方針に合わせて「$$...$$ を使う」「$$ の前後は空行」「$$ の中身は詰める」
# さらにユーザー要望に合わせ、数式部分も Python コメント（#）としてコメントアウトして載せる。

"""

from gurobipy import *


def mkp(I, J, v, a, b):
    """
    mkp -- multi-constrained knapsack (MKP) を解くためのGurobiモデルを構築して返す関数

    Parameters:
        - I: 次元集合（制約の種類）例: [1,2,...]
        - J: アイテム集合 例: [1,2,...]
        - v[j]: アイテム j の価値
        - a[i,j]: アイテム j の次元 i における消費量
        - b[i]: 次元 i の容量（上限）

    Returns:
        - model: 制約・目的関数まで設定済みのGurobi Model（optimize() で解ける状態）
    """

    # ------------------------------------------------------------
    # モデル作成
    # ------------------------------------------------------------
    model = Model("mkp")

    # ------------------------------------------------------------
    # 変数の作成
    # ------------------------------------------------------------
    # x[j] ∈ {0,1} : アイテム j を選ぶなら 1、選ばないなら 0
    #
    # # 数式（コメント）
    #
    # $$
    # x_j \in \{0,1\} \quad (\forall j \in J)
    # $$
    #
    x = {}
    for j in J:
        # vtype="B" は binary（二値）を意味する。
        # name を付けるとログや出力で追いやすい（x(1), x(2), ...）。
        x[j] = model.addVar(vtype="B", name="x(%s)" % j)

    # addVar で追加した変数を確定させる（古典的書き方。最近のgurobipyでは不要なこともある）。
    model.update()

    # ------------------------------------------------------------
    # 容量制約（複数次元）
    # ------------------------------------------------------------
    # 各次元 i について、選んだアイテムの消費量合計が容量 b[i] を超えないようにする。
    #
    # # 数式（コメント）
    #
    # $$
    # \sum_{j \in J} a_{ij} x_j \le b_i \quad (\forall i \in I)
    # $$
    #
    # ここで a[i,j] は「次元 i の消費量」、b[i] は「次元 i の容量」。
    #
    for i in I:
        # quicksum は線形和を高速に構築するGurobi推奨関数。
        model.addConstr(quicksum(a[i, j] * x[j] for j in J) <= b[i], "Capacity(%s)" % i)

    # ------------------------------------------------------------
    # 目的関数（価値最大化）
    # ------------------------------------------------------------
    # 選んだアイテムの価値 v[j] の合計を最大化する。
    #
    # # 数式（コメント）
    #
    # $$
    # \max \sum_{j \in J} v_j x_j
    # $$
    #
    model.setObjective(quicksum(v[j] * x[j] for j in J), GRB.MAXIMIZE)

    model.update()
    return model


def example():
    """
    サンプルデータを生成する関数。
    - J, v: アイテム集合と価値
    - a: 各次元の消費量（辞書）
    - I, b: 次元集合と容量
    """
    # J はアイテム集合、v は価値の辞書。
    J, v = multidict({1: 16, 2: 19, 3: 23, 4: 28})

    # a[(i,j)] = 次元 i におけるアイテム j の消費量
    # ここでは次元が 2つ：
    # - 次元1: 小さい重み（2,3,4,5）
    # - 次元2: 大きい重み（3000,3500,5100,7200）
    a = {
        (1, 1): 2,
        (1, 2): 3,
        (1, 3): 4,
        (1, 4): 5,
        (2, 1): 3000,
        (2, 2): 3500,
        (2, 3): 5100,
        (2, 4): 7200,
    }

    # I は次元集合、b は容量の辞書
    # 次元1の容量は 7、次元2の容量は 10000。
    I, b = multidict({1: 7, 2: 10000})

    return I, J, v, a, b


if __name__ == "__main__":
    # ------------------------------------------------------------
    # 例題データでMKPを解く
    # ------------------------------------------------------------
    I, J, v, a, b = example()

    # モデル構築
    model = mkp(I, J, v, a, b)

    # 最適化（MIPソルバが0/1最適解を探索）
    # MKPは一般にNP困難だが、アイテム数が小さければ即座に解けることが多い。
    model.optimize()

    # 最適目的値（最大価値）
    # print は Python3 形式に統一。
    print("Optimal value=", model.ObjVal)

    # ------------------------------------------------------------
    # 解の表示（選ばれたアイテムのみ）
    # ------------------------------------------------------------
    # EPS: 数値誤差対策。二値でも 1.0 ではなく 0.999999 のようになることがあるため。
    EPS = 1.0e-6

    for var in model.getVars():
        # var.X は最適解での変数値
        if var.X > EPS:
            # 選ばれたアイテム（x(j)=1）を表示
            print(var.VarName, var.X)

    # ------------------------------------------------------------
    # このコードが解いている最適化問題のまとめ
    # ------------------------------------------------------------
    # 変数:
    #
    # $$
    # x_j \in \{0,1\} \quad (\forall j \in J)
    # $$
    #
    # 制約:
    #
    # $$
    # \sum_{j \in J} a_{ij} x_j \le b_i \quad (\forall i \in I)
    # $$
    #
    # 目的:
    #
    # $$
    # \max \sum_{j \in J} v_j x_j
    # $$
    #
    # 解釈:
    # - 各次元 i の容量 b_i を超えない範囲でアイテムを選び、総価値を最大化する。
    # - 次元が増えるほど制約が厳しくなり、単一制約のナップサックより難しくなることが多い。
