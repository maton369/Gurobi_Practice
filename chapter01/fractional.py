"""
fractional.py:

Fractional optimization problem（分数目的の最適化）を、線形計画（LP）として解ける形に変形して
Gurobiで解く例。

このコードがやっていること（直感）
- 本来は「ある比（分数）を最適化する」タイプの問題を解きたい。
- 分数目的（例： (線形式)/(線形式) ）は、そのままだと一般に線形ではない（＝LPにならない）。
- そこで、Charnes–Cooper 変換の典型形で「スケーリング変数 t」を導入し、
  分数を“線形”な問題に写像して解いている。

このファイルのモデルは、前のパズル（頭・足）制約を「割合（比率）」として扱う形になっている。
ポイントは「t で全体をスケーリングして、比率の世界で最適化している」こと。

"""

from gurobipy import *

# ------------------------------------------------------------
# モデル作成
# ------------------------------------------------------------
# "fractional 1" という名前で最適化モデル（問題の器）を作る。
model = Model("fractional 1")

# ------------------------------------------------------------
# 変数の作成
# ------------------------------------------------------------
# x, y, z, t は連続変数（addVar() のデフォルト）。
# 典型的なCharnes–Cooper変換では、
#   t = 1 / (分母の線形式)
#   x, y, z = (元の変数) * t
# のような意味を持たせることが多い。
#
# このコードでも t は「スケール（正規化）のための変数」として機能し、
# 最後に x/t, y/t, z/t として元のスケールに戻している。
x = model.addVar()
y = model.addVar()
z = model.addVar()
t = model.addVar()

model.update()

# ------------------------------------------------------------
# 制約の追加
# ------------------------------------------------------------
# 以下の2本は、いわゆる「頭の数」「足の数」の関係式を
# t 倍した形として書いている。
#
# 元の（スケーリング前の）変数を (X, Y, Z) とすると、
# ここでは
#   x = X * t
#   y = Y * t
#   z = Z * t
# のように見なせるので、
#   X + Y + Z = 32
#   2X + 4Y + 8Z = 80
# を両辺 t 倍した
#   x + y + z = 32 t
#   2x + 4y + 8z = 80 t
# という形が出てくる。
#
# つまり、t を介して「(X,Y,Z) の比率として満たすべき制約」を線形に表している。
model.addConstr(x + y + z == 32 * t)
model.addConstr(2 * x + 4 * y + 8 * z == 80 * t)

# 3本目の制約は、スケーリングの“基準”を決めるための正規化制約。
#
#   2x + 4y == 1
#
# これは「(2x + 4y) を 1 に固定する」ことで、t が勝手に無限大/無限小へ
# スケールしてしまう自由度を潰している。
#
# もし元の変数 (X,Y,Z) で見たければ、
# x = X t, y = Y t なので
#
#   2(X t) + 4(Y t) = 1
#
# より
#
#   t (2X + 4Y) = 1
#
# したがって
#
#   t = 1 / (2X + 4Y)
#
# となり、これはCharnes–Cooper変換の典型形
# 「t が分母の逆数になる」状況そのものになっている。
#
# この制約があることで、目的関数や他の制約も “分数 → 線形” の形に落ちる。
model.addConstr(2 * x + 4 * y == 1)

# ------------------------------------------------------------
# 目的関数
# ------------------------------------------------------------
# 目的は x + y の最小化。
#
# Charnes–Cooper変換の見方をすると、元の変数での目的は
#   minimize (X + Y) / (2X + 4Y)
# のような「分数目的」になっていると解釈できる。
#
# 実際に、x = X t, y = Y t, t = 1/(2X+4Y) なので
#   x + y = (X+Y) t = (X+Y)/(2X+4Y)
# となり、線形目的 x+y の最小化は「分数の最小化」に一致する。
#
# ただし、この一致は「t を分母の逆数として固定する（正規化制約を入れる）」ことで成立している。
#
# ユーザー方針に合わせ、数式は $$...$$ を使い、前後に空行、内部は詰める。
#
# $$
# \min\ x + y
# $$
#
# （元の分数目的の解釈例）
#
# $$
# \min\ \frac{X + Y}{2X + 4Y}
# $$
#
model.setObjective(x + y, GRB.MINIMIZE)

# ------------------------------------------------------------
# 最適化
# ------------------------------------------------------------
# ここまでで、全て線形（制約も目的も線形）なのでLPとして解ける。
# optimize() を呼ぶと、Gurobi内部のLPソルバが解を計算する。
model.optimize()

# ------------------------------------------------------------
# 解の出力
# ------------------------------------------------------------
# 出力では
#   t（スケール変数）
#   x/t, y/t, z/t（元のスケールに戻した推定値）
# を表示している。
#
# x/t = (X t)/t = X なので、これが「元の変数（比率としての解）」に対応する。
#
# 注意:
# - t が 0 に近いと割り算が不安定になるが、ここでは制約 2x+4y=1 があるので
#   通常は t が 0 にはなりにくい構造になっている。
#
# print は Python3 形式の print() に統一する方針。
print("Opt. Val.=", model.ObjVal, ", t=", t.X)
print("(x,y,z)=", x.X / t.X, y.X / t.X, z.X / t.X)

# ------------------------------------------------------------
# モデルの数式まとめ（推定される元問題の形）
# ------------------------------------------------------------
# このLPが解いている（元の分数問題として読める）構造は次のように理解できる。
#
# 変数（元の変数を X,Y,Z とする）：
#
# $$
# X,\ Y,\ Z \ge 0
# $$
#
# 制約（頭・足）：
#
# $$
# X + Y + Z = 32
# $$
#
# $$
# 2X + 4Y + 8Z = 80
# $$
#
# 分数目的（例）：
#
# $$
# \min\ \frac{X + Y}{2X + 4Y}
# $$
#
# これを Charnes–Cooper 変換で
#   t = 1/(2X+4Y), x=Xt, y=Yt, z=Zt
# と置くと、線形な形（このコードの形）に変形できる、という流れである。
#
# この例は「分数目的を線形化してLPで解く」考え方のデモとして読むと理解しやすい。
