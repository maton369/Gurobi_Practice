"""
puzzle.py: solve a simple puzzle using gurobi

問題文（日本語意訳）
- 砂浜に「ツル（cranes）」「カメ（turtles）」「タコ（octopuses）」がいる。
- 全部の「頭の数」は 32。
- 全部の「脚の数」は 80。
- この条件を満たす組合せのうち、「カメとタコの数（y+z）」が最小になるようにしたい。
  （= なるべくツルを多くしたい、と同義）

補足
- ツルは 2本脚、カメは 4本脚、タコは 8本脚。
- これは「連立一次方程式＋非負整数制約」の問題であり、
  Gurobi的には「整数線形計画（ILP）」として解く。

"""

from gurobipy import *

# モデル（最適化問題の入れ物）を作る。
# モデルには「変数」「制約」「目的関数」「各種パラメータ」が格納され、optimize()で解かれる。
model = Model("puzzle")

# 変数の定義（すべて整数変数）
# x, y, z はそれぞれ「ツル」「カメ」「タコ」の個体数に対応する。
# vtype="I" は Integer（整数変数）を意味する。
# 整数制約が入るので、問題は LP ではなく ILP（整数線形計画）になる。
#
# 注意: lb（下限）を指定していないのでデフォルト lb=0（非負）になる。
# つまり x,y,z は 0 以上の整数として扱われる（負の個体数は許されない）。
x = model.addVar(vtype="I", name="x")  # x: cranes（ツル）の数
y = model.addVar(vtype="I", name="y")  # y: turtles（カメ）の数
z = model.addVar(vtype="I", name="z")  # z: octopuses（タコ）の数

# 変数を内部的に確定させる処理。
# 近年のgurobipyでは必須でない場面もあるが、古典的な書き方として残っている。
model.update()

# 制約1: 頭の数（Heads）
# ツル・カメ・タコはいずれも「頭は1つ」なので、
# x + y + z = 総頭数 = 32
#
# addConstr(式, 名前) の形で、制約に名前を付けている。
# 制約名を付けると、ログやIIS解析（不可能性の原因特定）で追いやすい。
model.addConstr(x + y + z == 32, "Heads")

# 制約2: 脚の数（Legs）
# ツル: 2本脚、カメ: 4本脚、タコ: 8本脚 より
# 2x + 4y + 8z = 総脚数 = 80
model.addConstr(2 * x + 4 * y + 8 * z == 80, "Legs")

# 目的関数: y + z を最小化
# 「カメとタコの合計数」を最小にしたい、という要求を数理的に表している。
# これは「ツル（x）をできるだけ多くしたい」と同値である理由:
#
# 制約 x + y + z = 32 より x = 32 - (y + z)
# なので (y + z) を最小化することは x を最大化することに一致する。
model.setObjective(y + z, GRB.MINIMIZE)

# 最適化を実行。
# ILPなので、内部では分枝限定法（Branch-and-Bound）やカット（Cuts）等を用いて
# 整数制約を満たしつつ最適解を探索する。
model.optimize()

# 結果の出力
# model.ObjVal は最適目的値（ここでは最小の y+z）。
# 変数値は x.X のように .X 属性で参照できる（小文字 .x を使う流儀もある）。
#
# 注意: 最適解が存在しない場合（infeasibleなど）にはこの値の参照は危険なので、
# 実務では model.status を確認してから表示するのが定石。
print("Opt. Val.=", model.ObjVal)
print("(x,y,z)=", (x.X, y.X, z.X))

# このモデルが解いている数理最適化問題をまとめると：
#
# 変数（整数・非負）:
#   x, y, z ∈ {0,1,2,...}
#
# 制約:
#   x + y + z = 32
#   2x + 4y + 8z = 80
#
# 目的:
#   minimize y + z
#
# つまり「頭数と脚数が一致する3種類の動物の個体数」を整数で決め、
# その中で「カメ＋タコが最小（=ツルが最大）」となる解を探している。
